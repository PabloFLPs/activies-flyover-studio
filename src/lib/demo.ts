export function buildDemo(): DemoActivity {
  const N = ROUTE.length;
  const pts: TrackPoint[] = ROUTE.map(([lat, lng], i) => {
    const u = i / (N - 1);
    const ang = u * Math.PI * 2;
    // Belo Horizonte centro sits around 850 m and is hilly; a couple of climbs.
    const ele =
      858 +
      22 * Math.sin(ang) +
      14 * Math.sin(ang * 2 + 0.7) +
      8 * Math.sin(ang * 5 + 1.3);
    // HR: warm up, hold a steady effort, small finishing lift.
    const hr = Math.round(
      118 +
        36 * Math.min(1, u * 3) +
        6 * Math.sin(ang * 4) +
        (u > 0.85 ? (12 * (u - 0.85)) / 0.15 : 0),
    );
    return { lat, lng, ele, hr, t: null };
  });

  // Timestamps from a ~5:35/km effort, nudged by grade.
  let time = Date.parse("2026-09-13T06:35:00-03:00");
  pts[0].t = time;
  for (let i = 1; i < pts.length; i++) {
    const d = hav(pts[i - 1], pts[i]);
    const slope = (pts[i].ele as number) - (pts[i - 1].ele as number);
    let pace = 335 + slope * 10 + 14 * Math.sin(i * 0.04); // s/km
    pace = Math.max(285, Math.min(430, pace));
    time += (d / 1000) * pace * 1000;
    pts[i].t = time;
  }

  return {
    points: pts,
    sport: "running",
    fileName: "belo-horizonte-run.gpx",
    athleteName: "Atleta Demo",
    location: "Centro & Savassi, Belo Horizonte",
  };
}
